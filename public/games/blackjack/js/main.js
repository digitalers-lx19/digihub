import { renderCards } from "/cards/ui.js";
const socket = io();
const $ = (id) => document.getElementById(id);
const state = { room: null, id: null, data: null };
const setError = (message) => { $("error").textContent = message; };
const join = () => {
    const room = $("roomInput").value.trim();
    if (!room) return setError("Escribe un código de sala");
    state.room = room;
    socket.emit("blackjack:join", { room, name: $("nameInput").value.trim() || "Jugador" });
};
const playerCard = (player) => {
    const box = document.createElement("div");
    box.className = "player";
    if (state.data?.turn === player.id) box.classList.add("player--turn");
    const title = document.createElement("h3");
    title.textContent = `${player.name}${player.id === state.id ? " (tú)" : ""}`;
    const info = document.createElement("p");
    info.textContent = `${player.score} pts · ${player.status} · ${player.chips} fichas · ${player.result ?? ""}`;
    const hand = document.createElement("div");
    hand.className = "hand";
    renderCards(hand, player.hand);
    box.append(title, info, hand);
    return box;
};
const render = () => {
    const data = state.data;
    if (!data) return;
    $("roomLabel").textContent = data.room;
    $("phaseLabel").textContent = data.phase;
    $("message").textContent = data.message;
    $("dealerScore").textContent = data.dealerScore;
    const turn = data.players.find((player) => player.id === data.turn);
    $("turnLabel").textContent = turn?.name ?? "—";
    renderCards($("dealer"), data.dealer);
    $("players").replaceChildren(...data.players.map(playerCard));
    const mine = data.turn === state.id && data.phase === "playing";
    $("hitBtn").disabled = !mine;
    $("standBtn").disabled = !mine;
    $("startBtn").disabled = state.id === null;
};
$("joinBtn").addEventListener("click", join);
$("startBtn").addEventListener("click", () => socket.emit("blackjack:start", { room: state.room }));
$("hitBtn").addEventListener("click", () => socket.emit("blackjack:hit", { room: state.room }));
$("standBtn").addEventListener("click", () => socket.emit("blackjack:stand", { room: state.room }));
socket.on("blackjack:joined", ({ id }) => { state.id = id; setError(""); $("startBtn").disabled = false; });
socket.on("blackjack:update", (data) => { state.data = data; render(); });
socket.on("blackjack:error", ({ message }) => setError(message));
socket.on("disconnect", () => { state.id = null; setError("Desconectado del servidor"); });
